def robot_xml(spec: Spec, trunk_z: float | None = None) -> str:
    """The trunk plus its four legs, identical in both worlds.

    `trunk_z` is where the trunk body is authored, in metres. None means
    `spec.stand_z` — wheels resting on z = 0 — which is what both MuJoCo worlds
    want and is why it is the default. Nothing in this repository passes
    anything else except the Isaac Lab conversion input.

    That override exists because Isaac Lab spawns a USD asset by creating a prim
    at `init_state.pos` and referencing the asset underneath it, so an authored
    trunk height is ADDED to the requested spawn height instead of replacing it.
    A 0.3634 m stance baked into the asset would put the machine 0.3634 m above
    where the caller asked for it and let it fall that far before the first
    reset writes a root pose. The stand height belongs to whoever places the
    robot, so `isaac/hound_usd.py` authors the trunk at the origin and
    `isaac/hound_cfg.py` supplies `spec.stand_z` as the spawn height.
    """
    hx, hy, hz = spec.trunk_half
    z = spec.stand_z if trunk_z is None else trunk_z
    legs = "".join(leg_xml(spec, n, sx, sy) for n, (sx, sy) in spec.legs.items())
    return f"""
    <body name="trunk" pos="0 0 {z:.4f}">
      <!-- Gymnasium's offscreen renderer looks up a camera named "track" when
           none is given (same as ant.xml); without it, eval videos fall back
           to a static free camera and the dog drives out of frame. -->
      <camera name="track" mode="trackcom" pos="0 -2.2 0.5" xyaxes="1 0 0 0 0.3 1"/>
      <joint name="root" type="free" armature="0" damping="0" stiffness="0" limited="false"/>

      <geom name="trunk_geom" type="box" size="{hx} {hy} {hz}" mass="{spec.trunk_mass}"
            rgba="0.22 0.23 0.26 1"/>
      <!-- Decoration only (class="deco": no mass, no contact). The head pod
           gives the machine a front, and the amber lens marks +X — the
           reward direction — so heading is readable in a still frame. Same
           trick as the spider's carapace lens. -->
      <geom class="deco" name="head_pod" type="box" size="0.055 0.052 0.040"
            pos="{hx + 0.035:.4f} 0 0.030" material="MatShell"/>
      <geom class="deco" name="head_lens" type="box" size="0.008 0.038 0.018"
            pos="{hx + 0.088:.4f} 0 0.034" material="MatLens"/>
      <geom class="deco" name="deck" type="box" size="{hx - 0.02:.4f} {hy - 0.004:.4f} 0.014"
            pos="-0.010 0 {hz + 0.012:.4f}" material="MatShell"/>
      <geom class="deco" name="tail_mast" type="capsule" size="0.007"
            fromto="{-hx - 0.01:.4f} 0 {hz:.4f}  {-hx - 0.07:.4f} 0 {hz + 0.075:.4f}"
            material="MatShell"/>
{legs}
    </body>"""


def actuator_xml(spec: Spec, control: str = "torque") -> str:
    """16 actuators, in the order the action vector uses.

    Per-leg blocks of four, legs in Spec.legs order. This block IS the
    contract for the action space — envs/hound.py's docstring quotes it,
    and robots/hound/check.py asserts the order.

    Two control modes, same 16 slots and same order in both:

    "torque"  every joint is a <motor>. ctrl is a fraction of peak torque,
              so `gear` IS the peak torque in N*m. What Hound-v0 uses.

    "pd"      the twelve leg joints become <position> servos: ctrl is a
              TARGET ANGLE in radians and MuJoCo runs
                  tau = kp * (target - q) - kv * qdot
              internally at the 200 Hz physics rate, TEN times per control
              step: frame_skip = 10 at timestep 0.005 s makes the policy act
              at 20 Hz, and 200 / 20 = 10. (This said "five" until 2026-07-28,
              when docs/lessons/scripts/pd_vs_torque_math.py read the two
              constants off the source instead of trusting the sentence.)
              The four wheels stay <motor>, because a wheel that turns
              forever has no pose to hold.

              forcerange keeps the same Go2 torque ceiling the torque model
              has, so the machine is no easier to drive — only easier to
              command.

              ctrlrange is each joint's own travel, written explicitly rather
              than via inheritrange: the <motor ctrlrange="-1 1"> default in
              common_head applies to every actuator type, not just <motor>,
              and MuJoCo rejects a model that sets both.
    """
    if control not in ("torque", "pd"):
        raise ValueError(f"control must be 'torque' or 'pd', got {control!r}")

    lo_a, hi_a = spec.abduct_range
    lo_h, hi_h = spec.hip_range
    lo_k, hi_k = spec.knee_range

    rows = []
    for name in spec.legs:
        if control == "torque":
            rows.append(f'    <motor name="{name}_abduct" joint="{name}_abduct" '
                        f'gear="{spec.gear_abduct}"/>')
            rows.append(f'    <motor name="{name}_hip"    joint="{name}_hip"    '
                        f'gear="{spec.gear_hip}"/>')
            rows.append(f'    <motor name="{name}_knee"   joint="{name}_knee"   '
                        f'gear="{spec.gear_knee}"/>')
        else:
            rows.append(f'    <position name="{name}_abduct" joint="{name}_abduct" '
                        f'kp="{spec.kp_abduct}" kv="{spec.kv_abduct}" '
                        f'ctrlrange="{lo_a} {hi_a}" '
                        f'forcerange="-{spec.gear_abduct} {spec.gear_abduct}"/>')
            rows.append(f'    <position name="{name}_hip"    joint="{name}_hip"    '
                        f'kp="{spec.kp_hip}" kv="{spec.kv_hip}" '
                        f'ctrlrange="{lo_h} {hi_h}" '
                        f'forcerange="-{spec.gear_hip} {spec.gear_hip}"/>')
            rows.append(f'    <position name="{name}_knee"   joint="{name}_knee"   '
                        f'kp="{spec.kp_knee}" kv="{spec.kv_knee}" '
                        f'ctrlrange="{lo_k} {hi_k}" '
                        f'forcerange="-{spec.gear_knee} {spec.gear_knee}"/>')
        rows.append(f'    <motor name="{name}_wheel"  joint="{name}_wheel"  '
                    f'gear="{spec.gear_wheel}"/>')
    return "\n".join(rows)


def keyframe_xml(spec: Spec) -> str:
    """The standing stance, shipped as a MuJoCo keyframe.

    envs/hound.py reads init_qpos straight out of this rather than
    recomputing the stance from Spec, so the pose the env spawns and the pose
    the springs are wound against can never drift apart — the XML is the one
    place both of them read. (Go2 ships its crouch the same way, as
    <key name="home">.)
    """
    q = [0.0, 0.0, spec.stand_z, 1.0, 0.0, 0.0, 0.0]
    for _ in spec.legs:
        q += [spec.stance_abduct, spec.stance_hip, spec.stance_knee, 0.0]
    return ('  <keyframe>\n    <key name="stance" qpos="'
            + " ".join(f"{v:.6g}" for v in q) + '"/>\n  </keyframe>')


def common_head(spec: Spec, model: str) -> str:
    """compiler / option / default / materials — shared by both worlds."""
    fs, ft, fr = spec.body_friction
    ws, wt, wr = spec.wheel_friction
    si0, si1, si2 = spec.wheel_solimp
    # inertiafromgeom="true": every body's inertia tensor is derived from its
    # geoms' SHAPES, scaled to the explicit `mass` on each geom. So the mass
    # budget stays readable as one number per link (Go2's real values) while
    # the inertia stays consistent with the geometry that number is spread
    # over — no hand-written 3x3s to drift out of sync with a length change.
    # The deco/hub classes carry density="0" and no mass, so they contribute
    # exactly nothing here.
    return f"""  <compiler angle="radian" coordinate="local" inertiafromgeom="true"/>
  <!-- integrator: implicitfast, NOT the RK4 the rest of this repo uses.
       RK4 evaluates the dynamics four times per step and treats damping
       explicitly, which is exactly the wrong trade for a machine whose
       fastest state is a lightly-damped wheel that can pass 40 rad/s.
       implicitfast integrates joint damping and armature implicitly, so the
       wheel stays stable at a timestep where RK4 rings. One eval per step at
       0.005 s is also CHEAPER than four evals at 0.01 s.
       timestep 0.005 with frame_skip=10 gives the same 20 Hz control rate as
       every other env here, over 200 Hz physics. -->
  <option integrator="implicitfast" timestep="0.005"/>

  <!-- Offscreen buffer for HD eval videos and for robots/hound/render.py. MuJoCo
       defaults to 640x480 and REFUSES a larger render rather than scaling,
       so this has to be declared here, in both worlds. -->
  <visual>
    <global offwidth="1920" offheight="1088"/>
    <quality shadowsize="4096"/>
  </visual>

  <default>
    <!-- Leg joints. stiffness/springref are set per-joint (the stance differs
         per joint); everything else is shared. -->
    <joint type="hinge" limited="true" armature="{spec.armature}"
           damping="{spec.damping}" frictionloss="{spec.frictionloss}"/>
    <geom condim="3" friction="{fs} {ft} {fr}" margin="0.001" group="0"/>
    <motor ctrllimited="true" ctrlrange="-1 1"/>

    <!-- The wheel hinge: unlimited, no spring, low rotor inertia. Everything
         about this class exists because a wheel is not a joint with a pose. -->
    <default class="wheel">
      <joint type="hinge" limited="false" stiffness="0"
             armature="{spec.wheel_armature}" damping="{spec.wheel_damping}"
             frictionloss="{spec.wheel_brake_torque():.4f}"/>
    </default>

    <!-- The tyre. priority=1 makes these friction values win outright over
         whatever surface it meets, instead of MuJoCo's default element-wise
         max — so the same tyre behaves the same on the plane and on sand.
         condim=6 is required for friction[2] (rolling resistance) to exist at
         all; at condim=3 a coasting wheel would roll forever. -->
    <default class="tyre">
      <geom condim="{spec.wheel_condim}" priority="1"
            friction="{ws} {wt} {wr}" solimp="{si0} {si1} {si2}"
            margin="{spec.wheel_margin}" material="MatTyre"/>
    </default>

    <!-- Visual-only geometry. density=0 AND mass unset so it adds nothing to
         the inertia; contype/conaffinity=0 so it never makes a contact. The
         physics is exactly what it would be with these deleted — the same
         invariant robots/spyder/check.py enforces for the spider's shell. -->
    <default class="deco">
      <geom contype="0" conaffinity="0" density="0" group="2"/>
    </default>
    <default class="hub">
      <geom contype="0" conaffinity="0" density="0" group="2"/>
    </default>
  </default>

  <asset>
    <!-- Joint colour code, same reading order as the spider: the hub at a
         joint tells you which axis it turns about. red = abduction (roll,
         +X), green = hip (pitch, +Y), blue = knee (pitch, +Y), amber = wheel. -->
    <material name="MatShell"  rgba="0.17 0.18 0.21 1" specular="0.6" shininess="0.55" reflectance="0.10"/>
    <material name="MatAbduct" rgba="0.76 0.17 0.16 1" specular="0.5" shininess="0.40"/>
    <material name="MatHip"    rgba="0.15 0.65 0.25 1" specular="0.5" shininess="0.40"/>
    <material name="MatKnee"   rgba="0.20 0.40 0.85 1" specular="0.5" shininess="0.40"/>
    <material name="MatWheel"  rgba="0.82 0.55 0.12 1" specular="0.7" shininess="0.60"/>
    <material name="MatSpoke"  rgba="0.55 0.57 0.62 1" specular="0.7" shininess="0.60"/>
    <material name="MatTyre"   rgba="0.09 0.09 0.10 1" specular="0.15" shininess="0.10"/>
    <material name="MatLens"   rgba="0.95 0.62 0.15 1" specular="0.9" shininess="0.90" emission="0.45"/>
{{extra_assets}}  </asset>
"""


