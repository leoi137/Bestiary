from __future__ import annotations

import argparse
import math
from pathlib import Path

from bestiary import paths

ASSET_DIR = paths.ASSETS


class Spec:
    """Every dimension the machine is built from.

    Derived quantities are properties, never stored, so changing one length
    cannot leave a stale copy of itself in another constant.
    """

    # ── Trunk ────────────────────────────────────────────────────────────
    # Go2's base collision box (half-extents 0.1881 0.04675 0.057) and its
    # 6.921 kg body mass. The box is the whole chassis: battery, compute,
    # actuator drivers.
    trunk_half = (0.1881, 0.04675, 0.057)
    trunk_mass = 6.921

    # ── Leg attachment ───────────────────────────────────────────────────
    hip_x, hip_y = 0.1934, 0.0465   # abduction pivot in the trunk frame
    abduct_off = 0.0955             # abduction pivot -> hip pivot, along +/-Y

    # ── Link lengths ─────────────────────────────────────────────────────
    thigh_len = 0.213               # Go2, unchanged
    calf_len = 0.190                # Go2's 0.213, shortened to make room for
    wheel_r = 0.085                 # the wheel: 0.190 + 0.085 ~= 0.213 + foot
    wheel_w = 0.050                 # wheel width (full, not half)

    # ── Masses (kg) ──────────────────────────────────────────────────────
    # First three are Go2's. The wheel is a hub-motor estimate: a 170 mm
    # rim + stator at 0.45 kg is in line with the 2 kg-class hub drives on
    # wheeled quadrupeds, and deliberately a little heavy — a light wheel is
    # the easy case, and unsprung mass at the ankle is what makes wheeled
    # legs hard to control.
    hip_mass, thigh_mass, calf_mass, wheel_mass = 0.678, 1.152, 0.241, 0.45

    # ── Joint ranges (rad) ───────────────────────────────────────────────
    abduct_range = (-0.80, 0.80)    # +/-46 deg; Go2 allows +/-60
    hip_range = (-1.20, 2.60)
    knee_range = (-2.60, -0.60)     # knee only ever folds one way, like Go2's
    # The wheel has no range at all — see the module docstring.

    # ── Standing stance (rad) ────────────────────────────────────────────
    # hip is the input; the knee is SOLVED (see stance_knee) so the wheel
    # ends up directly under its own hip pivot. A stance with the contact
    # patch offset from the pivot pushes the machine sideways the moment it
    # takes weight, which reads as a drifting robot and is nobody's intent.
    stance_abduct = 0.0
    stance_hip = 0.75

    # ── Actuation ────────────────────────────────────────────────────────
    # ctrlrange is [-1, 1] everywhere (the repo convention), so `gear` IS the
    # peak joint torque in N*m. Leg values are Go2's rated torques; the knee
    # is scaled by our shorter calf (Go2 rates 45.43 N*m over 0.213 m).
    gear_abduct = 23.7
    gear_hip = 23.7
    gear_knee = 40.0
    # Wheel: see Spec.report(). 3.0 N*m sits just under the traction limit.
    gear_wheel = 3.0

    # ── PD position control (the HoundPD-v0 variant) ─────────────────────
    # Used only when build(control="pd"). The twelve leg joints become
    # position servos; the four wheels stay on torque, because a wheel that
    # spins forever has no pose to hold and a position target on it is
    # meaningless.
    #
    # kp in N*m/rad, kv in N*m/(rad/s). These are the gains the hand
    # controller in robots/hound/play.py already uses. They are the only
    # gains on this machine that have been shown to hold the stance and
    # re-pose it without fighting the physics into instability, so the PD
    # variant starts from them rather than from a fresh guess. See
    # docs/theory/pd-control.md for the damping-ratio check.
    kp_abduct = 60.0
    kp_hip = 80.0
    kp_knee = 90.0
    kv_abduct = 3.0
    kv_hip = 4.0
    kv_knee = 4.5

    # Radians either side of the standing stance that the policy may command.
    # The action stays in [-1, 1] (the repo convention) and the env maps it to
    # target = stance + action * action_scale, so a zero action IS the stance.
    # That is the whole prior: the policy starts at "standing" instead of
    # having to discover it.
    action_scale = 0.5

    # ── Joint dynamics ───────────────────────────────────────────────────
    armature = 0.01                 # Go2's reflected rotor inertia
    damping = 1.5
    frictionloss = 0.2
    # A spring toward the standing stance. NOT physical — real Go2 joints have
    # no springs — but the same crutch spyder12.xml uses (stiffness=30), and
    # for the same reason: it makes the machine self-supporting at reset, so
    # SAC spends its first 50k steps learning to move rather than learning to
    # not collapse.
    #
    # The stiffnesses are DERIVED, not typed (see static_torques / stiffness).
    # The first pass at this file guessed 6 / 12 / 12 N*m/rad and the machine
    # folded to a 0.18 m belly-flop the moment gravity was switched on: the
    # knee alone has to hold ~5 N*m in this stance, so 12 N*m/rad buys 0.4 rad
    # of droop per leg. Sizing from the free-body diagram instead makes the
    # sag a design input and the stiffness the output.
    #
    # sag_target is the whole trade. Stiffer = less droop at reset, but a
    # spring the motor has to fight also eats control authority, because the
    # joint's reachable band at full torque is springref +/- gear/stiffness.
    # With the springs preloaded (see springref) this is no longer a droop at
    # all — the machine stands exactly where it is drawn — but it still sets
    # the stiffnesses, and through them how much travel the motors keep.
    #
    # 0.16 rad is a floor, not a preference. The knee is the binding joint:
    # its reachable band is springref +/- gear/k = (stance + s) +/- 7.63*s,
    # and covering the full [-2.60, -0.60] range needs s >= 0.154. Anything
    # softer than that and the spring, not the mechanism, decides how far the
    # knee can straighten.
    sag_target = 0.16

    # ...and sag_target is not the only constraint, because a wheeled leg is
    # an INVERTED PENDULUM and holding a load is not the same as holding it
    # STABLY. See critical_stiffness() for the derivation; the short version
    # is that a spring merely strong enough to carry the static load lets the
    # machine slide into the splits, which is what the second draft of this
    # file did (front wheels rolled 15 cm forward, trunk fell to 0.25 m).
    #
    # So the hip spring is sized to this multiple of its stability threshold.
    # 1.6 is measured, not chosen: sweeping the hip against a passive settle,
    # a settle from a +/-0.1 rad noisy reset, and a 25 cm drop, the machine
    # first stands cleanly in all three at ~18 N*m/rad = 1.55x the 11.6
    # threshold. At exactly 1.0x it still folds — a critical stiffness is
    # where instability starts, not where stability is comfortable.
    #
    # The cost is real and is reported: the hip keeps ~2.5 rad of its 3.8 rad
    # range at full motor torque. That is far more than a gait needs, and the
    # metric is pessimistic anyway (it assumes the motor fights the spring
    # with no help from gravity or ground reaction), but it IS the price of
    # the crutch. Set the stiffnesses to 0 for the physically pure machine —
    # it then has to learn to stand up before it can learn to move.
    stability_margin = 1.6

    # Wheel-specific. Rotor inertia is LOW on a direct-drive hub (no gearbox
    # to reflect), and damping is low because a wheel is supposed to coast —
    # rolling resistance is modelled at the CONTACT (friction[2]), which is
    # where it physically comes from, not as joint damping, which would also
    # (wrongly) resist the wheel while it is in the air.
    wheel_armature = 0.004
    wheel_damping = 0.05
    # wheel frictionloss is DERIVED — see wheel_brake_torque().

    # ── Contact ──────────────────────────────────────────────────────────
    # MuJoCo friction is (sliding, torsional, rolling). The wheel sets
    # priority="1" so ITS numbers win over the floor's instead of the usual
    # element-wise max — a wheel's contact is a property of the tyre, and we
    # want the same tyre on the plane and on sand.
    #   sliding 0.9   traction; above this the wheel just spins
    #   torsional 0.03 resists pivoting about the contact normal. Without it a
    #                 standing machine can yaw for free on four point contacts.
    #   rolling 0.002 rolling resistance. This is the term that makes a
    #                 coasting wheel eventually stop, and it needs condim=6.
    wheel_friction = (0.9, 0.03, 0.002)
    # condim=3 (sliding only), so friction[1] and [2] above are inert. That is
    # deliberate and it cost a sweep to settle: condim=6 buys contact-level
    # torsional and rolling resistance, but on the DESERT it also settles 4 mm
    # lower and drifts twice as far, because every extra constraint per contact
    # is another chance for the heightfield's imperfect contact normals to
    # disagree with each other. Rolling resistance moves to the wheel joint
    # instead (wheel_brake_torque), where it is numerically boring and, for a
    # geared hub drive, arguably more honest anyway. The values are left in
    # place so switching back to condim=6 is a one-character experiment.
    wheel_condim = 3
    # margin=0, not the 1 mm used elsewhere. Margin makes contacts appear
    # BEFORE touchdown, and on a heightfield those early contacts are found
    # against the vertical walls of the terrain-cell prisms — normals pointing
    # sideways, into a wheel that is supposed to be rolling. At margin 0.001
    # the machine spawned with 11-18 horizontal-normal contacts and was kicked
    # over; at margin 0 it stands at 0.3630 with upright 1.000.
    wheel_margin = 0.0
    # Contact softness. This one line cost more debugging than everything
    # else in the file combined, so it gets the long comment.
    #
    # The first draft copied Go2's foot verbatim: solimp="0.015 1 0.022".
    # That is a deliberately SOFT contact — dmin=0.015 means the constraint
    # is nearly free at small penetration — and it is correct *for Go2*,
    # because go2.xml also sets <option cone="elliptic" impratio="100"/>,
    # which stiffens the normal direction back up. Copy the foot without the
    # option and you get the softness with none of the compensation: the
    # wheels sank 9 mm into the floor, the machine settled 8 cm low, pitched
    # 18 deg nose-up and dumped its rear thighs on the ground. Every spring
    # theory above was tested against that and came out wrong, because the
    # springs were never the problem.
    #
    # A firm contact instead. With this the machine settles 0.3 mm below the
    # height it is drawn at, which is the correct answer for a rigid wheel on
    # rigid ground, and it survives a 25 cm drop without grounding anything.
    wheel_solimp = (0.95, 0.99, 0.001)
    body_friction = (0.9, 0.5, 0.5)

    legs = {  # name: (x sign, y sign)
        "FL": (+1, +1),
        "FR": (+1, -1),
        "RL": (-1, +1),
        "RR": (-1, -1),
    }

    # ── Derived ──────────────────────────────────────────────────────────
    @property
    def stance_knee(self) -> float:
        """Knee angle that puts the wheel axle directly under the hip pivot.

        Forward kinematics in the leg's sagittal plane, with both pitch
        joints rotating about +Y. A rotation of theta about +Y maps the
        straight-down link vector (0, 0, -L) to (-L sin(theta), 0, -L cos(theta)),
        so positive pitch swings a link BACKWARD (-X) and up. Requiring zero
        net X offset at the axle:

            L_thigh * sin(hip) + L_calf * sin(hip + knee) = 0

        which inverts to knee = -asin(L_thigh sin(hip) / L_calf) - hip. The
        thigh's reach must be inside the calf's or there is no solution, hence
        the assert: that is the geometric statement "you cannot fold a long
        link back under a short one".
        """
        reach = self.thigh_len * math.sin(self.stance_hip)
        assert abs(reach) <= self.calf_len, (
            f"stance_hip={self.stance_hip} throws the knee {reach:.3f} m out, "
            f"which the {self.calf_len:.3f} m calf cannot pull back under the hip"
        )
        knee = -math.asin(reach / self.calf_len) - self.stance_hip
        assert self.knee_range[0] <= knee <= self.knee_range[1], (
            f"solved stance knee {knee:.3f} rad is outside {self.knee_range}"
        )
        return knee

    @property
    def axle_drop(self) -> float:
        """Hip pivot -> wheel axle, vertically, in the standing stance."""
        return self.thigh_len * math.cos(self.stance_hip) + self.calf_len * math.cos(
            self.stance_hip + self.stance_knee
        )

    @property
    def stand_z(self) -> float:
        """Trunk-origin height with the wheels resting on z = 0.

        The abduction pivots sit at the trunk origin's z, so this is just the
        axle drop plus the wheel radius. Written into the flat model's trunk
        `pos`; on the desert model HoundEnv re-bases it off the measured
        ground height, exactly as SpyderEnv does.
        """
        return self.axle_drop + self.wheel_r

    # ── Static analysis: what each spring actually has to hold ───────────
    #
    # All of this is one free-body diagram of a single leg carrying a quarter
    # of the machine, evaluated in the standing stance. It exists because the
    # alternative — guessing stiffnesses — produced a robot that folded flat.
    #
    # Leg-local coordinates: origin at the HIP pivot, +x forward, +z up, all
    # in the leg's sagittal plane. A pitch of theta about +Y maps (0,0,-L) to
    # (-L sin theta, 0, -L cos theta), the same convention stance_knee uses.
    def _leg_points(self) -> dict[str, tuple[float, float]]:
        t1 = self.stance_hip
        t2 = self.stance_hip + self.stance_knee
        knee = (-self.thigh_len * math.sin(t1), -self.thigh_len * math.cos(t1))
        axle = (knee[0] - self.calf_len * math.sin(t2),
                knee[1] - self.calf_len * math.cos(t2))
        return {
            "knee": knee,
            "axle": axle,
            "thigh_com": (knee[0] / 2.0, knee[1] / 2.0),
            "calf_com": ((knee[0] + axle[0]) / 2.0, (knee[1] + axle[1]) / 2.0),
            # The ground pushes up through the contact patch, which sits
            # directly below the axle — and, by stance_knee's construction,
            # directly below the hip pivot too.
            "contact": (axle[0], axle[1] - self.wheel_r),
        }

    def static_torques(self) -> dict[str, float]:
        """SIGNED gravity torque on each leg joint in the standing stance, N*m.

        The ground reaction on one wheel is a quarter of the machine's weight
        pushing straight up; every link's own weight pulls straight down. A
        joint's load is the net moment of everything distal to it.

        Signs matter here — they decide which way each spring must be wound
        (see springref) — so the moments are taken properly rather than as
        magnitudes. For the pitch joints, a vertical force F_z at a position
        r from the pivot makes a torque about +Y of -r_x * F_z. For abduction,
        which turns about +X, it is +r_y * F_z. Values are quoted for a LEFT
        leg; abduction mirrors with the leg's y sign, the other two do not.
        """
        g = 9.81
        p = self._leg_points()
        n = self.total_mass * g / 4.0        # ground reaction, one wheel

        # Knee: everything below it is the calf, the wheel, and the contact.
        knee = (
            -(p["contact"][0] - p["knee"][0]) * n
            - (p["calf_com"][0] - p["knee"][0]) * (-g * self.calf_mass)
            - (p["axle"][0] - p["knee"][0]) * (-g * self.wheel_mass)
        )

        # Hip: the ground reaction's line of action passes through the hip
        # pivot (contact x == 0), so it contributes NOTHING and all that is
        # left is the leg's own dead weight. That near-cancellation is the
        # whole point of solving for stance_knee — a stance with the wheel
        # offset from the hip would make this the largest load on the machine.
        hip = (
            -p["contact"][0] * n
            - p["thigh_com"][0] * (-g * self.thigh_mass)
            - p["calf_com"][0] * (-g * self.calf_mass)
            - p["axle"][0] * (-g * self.wheel_mass)
        )

        # Abduction turns about +X, so its lever arm is the sideways offset
        # from the abduction pivot, not the fore-aft one. Everything distal
        # hangs a full abduct_off outboard; the abduction link itself is a
        # bar spanning the offset, so its own weight acts at half of it.
        limb = self.thigh_mass + self.calf_mass + self.wheel_mass
        abduct = (
            self.abduct_off * (n - g * limb)
            + (self.abduct_off / 2.0) * (-g * self.hip_mass)
        )
        return {"abduct": abduct, "hip": hip, "knee": knee}

    def critical_stiffness(self) -> dict[str, float]:
        """Spring rate below which the standing stance is UNSTABLE, N*m/rad.

        THE defining mechanical difference between this machine and the
        spider, and the reason a wheel is not just "a foot that spins".

        A point foot grips. Push a legged robot's shin and the contact patch
        holds still, so the leg pivots about the FOOT and the geometry fights
        back. A wheel does not grip: it is free to roll, which means the
        contact patch is free to translate fore-aft. The leg therefore pivots
        about its own HIP with the ground offering no fore-aft resistance at
        all — a load balanced on a stick balanced on a cart.

        Formally: let h(q) be the height of the carried load above the contact
        patch. Gravitational potential is U = N*h, and an equilibrium is
        stable only where U is a local minimum. In the standing stance h is at
        a local MAXIMUM along the rolling directions (that is what "standing
        up" means), so d2U/dq2 is negative and the spring has to make up the
        difference. The joint is stable iff

            stiffness > -N * d2h/dq2                      [this function]

        Note what this does NOT apply to: abduction. A wheel is free along its
        rolling direction and grips across it, so the sideways lean the
        abduction joint controls still pivots about a contact patch that stays
        put. Exactly one of the three leg joints loses its passive stability,
        and it is the one whose motion rolls the wheel.

        This is also why the machine cannot simply stand: a real wheel-legged
        robot holds still by BRAKING its wheels, and a policy here has to
        learn the same thing. The springs only buy a stance at reset.
        """
        n = self.total_mass * 9.81 / 4.0
        t1 = self.stance_hip
        t2 = self.stance_hip + self.stance_knee
        # h = L1 cos(t1) + L2 cos(t1+t2) + r, differentiated twice.
        h_hip = -self.thigh_len * math.cos(t1) - self.calf_len * math.cos(t2)
        h_knee = -self.calf_len * math.cos(t2)
        return {"abduct": 0.0, "hip": -n * h_hip, "knee": -n * h_knee}

    def stiffness(self) -> dict[str, float]:
        """Spring rate per joint — the larger of two independent demands.

        Carry the static load within sag_target, AND clear the inverted-
        pendulum threshold with margin. report() prints both so it is visible
        which constraint sizes each joint: the knee and abduction are sized
        by load, the hip by stability, and nothing else is close.
        """
        crit = self.critical_stiffness()
        return {j: max(abs(t) / self.sag_target, self.stability_margin * crit[j])
                for j, t in self.static_torques().items()}

    def springref(self, y_sign: int = 1) -> dict[str, float]:
        """Spring rest angles — PRELOADED, not the stance itself.

        The bug this exists to fix is worth stating plainly, because it is
        invisible right up until the robot falls over. A spring produces zero
        torque at its own rest angle. Park springref ON the standing stance
        and the machine is released, at t=0, with every gram of its weight
        unopposed: ~5 N*m unbalanced at each knee. It drops, overshoots, and
        the hip's inverted-pendulum mode does the rest — the third draft of
        this file settled into a dog SIT, rear thighs flat on the floor,
        nose up 14 deg, and stiffer springs only made the sit deeper.

        So the springs are wound up in advance. Solving

            spring torque + gravity torque = 0   at   q = stance
            -k * (stance - springref) + tau_g = 0

        gives springref = stance - tau_g / k. And since k was defined as
        |tau_g| / sag_target, that offset is EXACTLY sag_target, wound
        AGAINST the direction gravity pulls:

            springref = stance + sign(-tau_g) * sag_target

        which is the whole idea in one line: wind each spring up by the
        deflection it would otherwise have sagged, and the authored stance
        becomes a true equilibrium — zero net torque, zero velocity, the
        machine simply stands there at the height it was drawn at.
        """
        tau, k = self.static_torques(), self.stiffness()
        tau = {**tau, "abduct": tau["abduct"] * y_sign}
        stance = {"abduct": self.stance_abduct, "hip": self.stance_hip,
                  "knee": self.stance_knee}
        return {j: stance[j] - tau[j] / k[j] for j in stance}

    def stability_deficit(self) -> dict[str, float]:
        """How much stiffness each joint is SHORT of stable, N*m/rad.

        Zero for every joint by construction — stiffness() takes the max with
        the threshold — so this exists as a self-check, asserted in report().
        """
        k, crit = self.stiffness(), self.critical_stiffness()
        return {j: max(0.0, crit[j] - k[j]) for j in crit}

    def wheel_brake_torque(self) -> float:
        """Breakaway torque of the hub drive, N*m.

        Not a stability device — the hip spring handles that, because the
        instability is the body rotating over a STATIONARY contact and a
        brake on the wheel does nothing about that. (An earlier draft of this
        file tried exactly that and it failed for precisely this reason: the
        wheels barely turned while the machine sat down around them.)

        Two jobs, one number. Physically it is the dry friction of a geared
        hub drive, and it is the ONLY thing that stops a coasting wheel now
        that condim=3 has removed contact-level rolling resistance — without
        it the machine would roll forever.

        The size, though, is set by the heightfield. 5% of rated torque is
        the plausible-hardware guess and it is enough on the flat plane; on
        the desert it is not, and 3/15 noisy resets ended on the floor. At
        13% every one of 15 stays up (upright >= 0.979) because a stiffer
        wheel shrugs off the impulsive kicks the hfield collider delivers
        instead of being spun down by them. So: partly hardware, partly
        numerics, and it would be dishonest to present it as purely the
        former. 13% breakaway is high for a direct-drive hub but ordinary
        for a geared one, so the machine it describes still exists.
        """
        return 0.133 * self.gear_wheel

    def is_stance_stable(self) -> tuple[bool, float]:
        """Positive-definiteness of the full (hip, knee) stiffness Hessian.

        The per-joint criterion above holds one joint while testing the other,
        but hip and knee are coupled — d2h/dhip.dknee is not zero — so a pair
        of individually-stable joints can still have an unstable mixed mode
        (the leg folding and swinging at once). The honest test is that

            K + N * d2h/dq2      for q = (hip, knee)

        is positive definite. Returns (ok, smallest eigenvalue).
        """
        n = self.total_mass * 9.81 / 4.0
        t1 = self.stance_hip
        t2 = self.stance_hip + self.stance_knee
        h11 = -self.thigh_len * math.cos(t1) - self.calf_len * math.cos(t2)
        h12 = -self.calf_len * math.cos(t2)
        h22 = -self.calf_len * math.cos(t2)
        k = self.stiffness()
        a, b, c = k["hip"] + n * h11, n * h12, k["knee"] + n * h22
        # Eigenvalues of the symmetric 2x2 [[a, b], [b, c]].
        mid = (a + c) / 2.0
        rad = math.sqrt(((a - c) / 2.0) ** 2 + b * b)
        lo = mid - rad
        return lo > 0.0, lo

    def authority(self) -> dict[str, float]:
        """Radians a motor at full torque can pull the joint off springref.

        The reachable band is springref +/- this. If it is narrower than the
        joint's own range, the spring — not the mechanism — is what limits
        the robot, which is a crutch that has become a cage.
        """
        gears = {"abduct": self.gear_abduct, "hip": self.gear_hip,
                 "knee": self.gear_knee}
        return {k: gears[k] / v for k, v in self.stiffness().items()}

    @property
    def total_mass(self) -> float:
        return self.trunk_mass + 4 * (
            self.hip_mass + self.thigh_mass + self.calf_mass + self.wheel_mass
        )

    @property
    def wheel_traction_torque(self) -> float:
        """Wheel torque at which the contact patch breaks loose, N*m.

        Static share of weight per wheel, times sliding friction, times the
        radius. This is the number that sizes gear_wheel: a hub motor geared
        past it cannot deliver more thrust, it can only spin.
        """
        normal = self.total_mass * 9.81 / 4.0
        return normal * self.wheel_friction[0] * self.wheel_r


