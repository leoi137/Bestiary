"""Turn spec.py into CAD parameters, STLs, and a machine-readable robot description.

    python -m bestiary.robots.whelp.export              # params + robot.json (no CAD needed)
    python -m bestiary.robots.whelp.export --stl        # ...and render every STL
    python -m bestiary.robots.whelp.export --stl --check-mass   # ...and verify the mass model

WHAT "SINGLE SOURCE OF TRUTH" MEANS HERE, AND WHY IT IS NOT build.scad
----------------------------------------------------------------------
The brief asked for build.scad to be the single source. It very nearly is, and
the difference is deliberate, so it is written down rather than assumed.

    spec.py          THE NUMBERS.    Every dimension, with provenance.
    geometry.py      THE DERIVATION. Stance solve, joint origins, axes.
    scad/*.scad      THE GEOMETRY.   How those numbers become solids.

`params_gen.scad` and `derived_gen.scad` are GENERATED from the first two by
this file and must never be hand-edited; check.py fails if regenerating them
changes anything. build.scad includes them, so the CAD has exactly one source
for every number and the assembly preview is posed at the same solved stance
angles the URDF carries.

The reason not to put the numbers in build.scad is that OpenSCAD cannot do the
work. The stance knee angle is the solution of an inverse-kinematics problem;
the design stress is a product of three measured knockdowns; the mass budget is
a parallel-axis sum over sixty primitives. Those belong in Python, and once they
are in Python, having a SECOND authoritative copy of the lengths in .scad is
precisely the duplication the rule exists to prevent.

And no STL is ever hand-edited, which was the actual point.

NOTHING EXCEPT STL GENERATION REQUIRES OpenSCAD
-----------------------------------------------
robot.json, the URDF, the torque report and every check run on plain Python.
That is not a convenience: a pipeline where regenerating the robot description
needs a CAD binary is a pipeline that breaks on the training machine, in CI, and
on anybody else's laptop. OpenSCAD is needed to produce printable geometry and
for nothing else.

THE CROSS-CHECK THAT MAKES THE MASS MODEL TRUSTWORTHY
-----------------------------------------------------
massmodel.py is a second, independent implementation of the geometry in
scad/parts/. Two implementations of one thing drift. So when OpenSCAD IS present,
`--check-mass` renders each part, measures the real mesh with stl.py, and asserts
the analytic volume agrees within massmodel.MASS_MODEL_TOL -- and separately that
every mesh is watertight, since the volume of an open mesh is not a volume, it is
just a number that a divergence-theorem sum happens to return.
"""
