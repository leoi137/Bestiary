_BANNER = (
    "// GENERATED by `python -m bestiary.robots.whelp.export`. DO NOT EDIT.\n"
    "//\n"
    "// Every number here comes from spec.py, which carries its provenance, or from\n"
    "// geometry.py, which derives it. check.py fails if regenerating this file changes\n"
    "// it, so a hand edit here is not merely discouraged -- it is caught.\n"
    "//\n"
    "// To change a dimension: edit spec.py, re-run export, commit both.\n"
    "\n"
)


def _scad_value(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return f"{v:.6f}".rstrip("0").rstrip(".") or "0"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return f'"{v}"'
    if isinstance(v, (tuple, list)):
        return "[" + ", ".join(_scad_value(x) for x in v) + "]"
    raise TypeError(f"cannot express {v!r} ({type(v).__name__}) in OpenSCAD")


